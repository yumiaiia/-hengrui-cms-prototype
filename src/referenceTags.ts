export const referenceDimensionOrder = referenceDimensions.map(
  (dimension) => dimension.name,
);
export const referenceTags: Tag[] = referenceDimensions.flatMap((dim) => {
  const dimensionId = refDimensionId(dim.name);
  const root: Tag = {
    id: dimensionId,
    name: dim.name,
    parentId: null,
    enabled: true,
    external: false,
    kind: dim.kind,
    cardinality: dim.cardinality,
    scope: dim.scope || "material",
    ai: dim.ai || "closed",
    merge: dim.merge || (dim.cardinality === "single" ? "priority" : "union"),
    fallbackId: dim.fallback ? refValueId(dim.name, dim.fallback) : undefined,
    humanEditable: dim.humanEditable,
  };
  return [
    root,
    ...dim.values.map((raw, index): Tag => {
      const value = typeof raw === "string" ? { name: raw } : raw;
      return {
        id: refValueId(dim.name, value.name),
        name: value.name,
        parentId: dimensionId,
        enabled: true,
        external: false,
        aliases: value.aliases,
        order: index + 1,
      };
    }),
  ];
});
